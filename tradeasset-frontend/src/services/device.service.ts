/**
 * Device Recognition Service
 * Handles device management and fingerprinting
 */

import { apiClient } from '../lib/api-client';
import { API_CONFIG } from '../config/constants';
import type { DeviceInfo, DeviceListResponse } from '../types/device.types';

export const deviceService = {
  /**
   * Get list of user's devices
   */
  async getDevices(): Promise<DeviceInfo[]> {
    const response = await apiClient.get<DeviceListResponse>(
      API_CONFIG.ENDPOINTS.AUTH.DEVICES
    );
    return response.data.devices;
  },

  /**
   * Trust or untrust a device
   */
  async trustDevice(fingerprint: string, trusted: boolean): Promise<{ message: string }> {
    const response = await apiClient.put<{ message: string }>(
      `${API_CONFIG.ENDPOINTS.AUTH.DEVICE_TRUST}/${fingerprint}/trust`,
      { trusted }
    );
    return response.data;
  },

  /**
   * Get current device fingerprint (generated by API client)
   */
  getCurrentDeviceFingerprint(): string {
    return apiClient.getDeviceFingerprint();
  },
};

